function ILAWSection({ title, children, editableValue, onSave }) {
  const [isEditing, setIsEditing] = useState(false);
  const [editValue, setEditValue] = useState(editableValue ?? "");

  useEffect(() => {
    if (!isEditing) setEditValue(editableValue ?? "");
  }, [editableValue, isEditing]);

  const handleSave = () => {
    onSave?.(editValue);
    setIsEditing(false);
  };

  return (
    <section className="rounded-2xl border border-white/10 bg-[#111722]">
      <div className="flex items-center justify-between border-b border-white/10 px-5 py-4">
        <h2 className="font-medium">{title}</h2>
        {onSave && !isEditing && (
          <button
            onClick={() => {
              setEditValue(editableValue ?? "");
              setIsEditing(true);
            }}
            className="rounded-lg px-3 py-1.5 text-xs text-gray-400 hover:bg-white/5 hover:text-white"
          >
            Edit
          </button>
        )}
      </div>

      <div className="p-5">
        {isEditing ? (
          <div>
            <textarea
              value={editValue}
              onChange={(e) => setEditValue(e.target.value)}
              rows={10}
              autoFocus
              className="w-full resize-y rounded-xl border border-green-500/30 bg-[#0b0f19] p-4 text-sm leading-6 text-gray-200 outline-none focus:border-green-500/60"
            />
            <div className="mt-4 flex justify-end gap-2">
              <button
                onClick={() => {
                  setEditValue(editableValue ?? "");
                  setIsEditing(false);
                }}
                className="rounded-lg border border-white/10 px-4 py-2 text-sm text-gray-400 hover:bg-white/5 hover:text-white"
              >
                Cancel
              </button>
              <button
                onClick={handleSave}
                className="rounded-lg bg-green-600 px-4 py-2 text-sm font-medium text-white hover:bg-green-500"
              >
                Save
              </button>
            </div>
          </div>
        ) : (
          children
        )}
      </div>
    </section>
  );
}

function EditableSession({ session, onSave }) {
  const [isEditing, setIsEditing] = useState(false);
  const [draft, setDraft] = useState(session);

  useEffect(() => {
    if (!isEditing) setDraft(session);
  }, [session, isEditing]);

  return (
    <div className="rounded-xl border border-white/10 bg-[#0b0f19] p-4">
      <div className="mb-4 flex items-center justify-between">
        <h3 className="text-base font-medium text-white">
          Session {session.session_number}
        </h3>
        {!isEditing && (
          <button
            onClick={() => {
              setDraft(session);
              setIsEditing(true);
            }}
            className="rounded-lg px-3 py-1.5 text-xs text-gray-400 hover:bg-white/5 hover:text-white"
          >
            Edit
          </button>
        )}
      </div>

      {isEditing ? (
        <div className="space-y-4">
          <EditorField
            label="Topic"
            value={draft.topic}
            onChange={(value) => setDraft({ ...draft, topic: value })}
          />
          <EditorField
            label="Learning Activities"
            value={draft.activities}
            rows={6}
            onChange={(value) => setDraft({ ...draft, activities: value })}
          />
          <EditorField
            label="Assessment"
            value={draft.assessment}
            rows={5}
            onChange={(value) => setDraft({ ...draft, assessment: value })}
          />
          <div className="flex justify-end gap-2">
            <button
              onClick={() => {
                setDraft(session);
                setIsEditing(false);
              }}
              className="rounded-lg border border-white/10 px-4 py-2 text-sm text-gray-400 hover:bg-white/5 hover:text-white"
            >
              Cancel
            </button>
            <button
              onClick={() => {
                onSave(draft);
                setIsEditing(false);
              }}
              className="rounded-lg bg-green-600 px-4 py-2 text-sm font-medium text-white hover:bg-green-500"
            >
              Save
            </button>
          </div>
        </div>
      ) : (
        <>
          <ContentBlock title="Topic" content={session.topic} />
          <ContentBlock
            title="Learning Activities"
            content={session.activities}
          />
          <ContentBlock title="Assessment" content={session.assessment} />
        </>
      )}
    </div>
  );
}

function EditorField({ label, value, onChange, rows = 4 }) {
  return (
    <div>
      <label className="mb-2 block text-sm font-medium text-gray-200">
        {label}
      </label>
      <textarea
        value={value ?? ""}
        onChange={(e) => onChange(e.target.value)}
        rows={rows}
        className="w-full resize-y rounded-xl border border-white/10 bg-[#111722] p-3 text-sm leading-6 text-gray-200 outline-none focus:border-green-500/50"
      />
    </div>
  );
}

