function ListBlock({ title, items }) {
  return (
    <div className="mb-5 last:mb-0">
      <h4 className="text-sm font-medium text-gray-200">{title}</h4>
      <ul className="mt-3 space-y-2">
        {(items ?? []).map((item, index) => (
          <li
            key={`${item}-${index}`}
            className="text-sm leading-6 text-gray-400"
          >
            • {item}
          </li>
        ))}
      </ul>
    </div>
  );
}

function textToList(value) {
  return value
    .split("\n")
    .map((item) => item.replace(/^[-•]\s*/, "").trim())
    .filter(Boolean);
}

function parseKeyValueText(value) {
  const result = {};
  value.split("\n").forEach((line) => {
    const index = line.indexOf(":");
    if (index === -1) return;
    const key = line.slice(0, index).trim();
    const content = line.slice(index + 1).trim();
    if (key) result[key] = content;
  });
  return result;
}

function parseLabeledSections(value) {
  const labels = [
    "Content Standard",
    "Performance Standard",
    "Learning Competencies",
    "Specific Objectives",
    "Learning Objectives",
    "Learner Context",
    "Learning Resources",
    "Pre-Lesson",
    "Flow / Daylong",
    "Discussion",
    "Deduction / Generalization",
    "Concepts",
    "Opportunities for Integration",
    "Formative Assessment",
    "Guide Questions",
    "Extended Learning Opportunities",
    "Reflections",
    "Application",
  ];
  const lines = value.split("\n");
  const result = {};
  let current = null;
  let buffer = [];

  const flush = () => {
    if (current) result[current] = buffer.join("\n").trim();
  };

  lines.forEach((line) => {
    const label = labels.find((item) => line.trim().startsWith(`${item}:`));
    if (label) {
      flush();
      current = label;
      buffer = [
        line
          .trim()
          .slice(label.length + 1)
          .trim(),
      ].filter(Boolean);
    } else if (current) {
      buffer.push(line);
    }
  });

  flush();
  return result;
}
