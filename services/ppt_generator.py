from pathlib import Path

from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.enum.text import PP_ALIGN
from pptx.dml.color import RGBColor

from services.theme_manager import get_theme
from services.image_search import get_slide_image
from pptx.util import Pt


def add_background(slide, prs, theme):
    background = slide.shapes.add_picture(
        str(theme["background"]),
        0,
        0,
        width=prs.slide_width,
        height=prs.slide_height
    )

    slide.shapes._spTree.remove(background._element)
    slide.shapes._spTree.insert(2, background._element)


def add_logo(slide, theme):

    logo = theme["logo"]

    if logo.exists():
        slide.shapes.add_picture(
            str(logo),
            Inches(8.0),
            Inches(0.35),
            width=Inches(0.8)
        )


def add_title(slide, text, theme):

    textbox = slide.shapes.add_textbox(
        Inches(1.8),
        Inches(1.2),
        Inches(8.2),
        Inches(1.0)
    )

    tf = textbox.text_frame
    p = tf.paragraphs[0]
    p.text = text

    p.font.name = theme["title_font"]
    p.font.size = Pt(32)
    p.font.bold = True
    p.font.color.rgb = RGBColor(34, 34, 34)

    p.alignment = PP_ALIGN.LEFT

def add_subtitle(slide, text, theme):

    textbox = slide.shapes.add_textbox(
        Inches(1.8),      # align with title
        Inches(1.85),     # moved down
        Inches(8),
        Inches(0.4)
    )

    tf = textbox.text_frame
    p = tf.paragraphs[0]

    p.text = text
    p.font.name = theme["body_font"]
    p.font.size = Pt(16)
    p.font.color.rgb = theme["body_color"]


def add_bullets(slide, bullets, theme):

    textbox = slide.shapes.add_textbox(
        Inches(0.8),
        Inches(1.75),
        Inches(5.2),
        Inches(4.6)
    )

    tf = textbox.text_frame
    tf.word_wrap = True

    for i, bullet in enumerate(bullets):

        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()

        p.text = f"• {bullet}"      # <-- add bullet back
        p.level = 0
        p.space_after = Pt(8)

        p.font.name = theme["body_font"]
        p.font.size = Pt(18)
        p.font.color.rgb = theme["body_color"]


