def create_presentation(title, slides):

    theme = get_theme("business")

    output_dir = Path("generated")
    output_dir.mkdir(exist_ok=True)

    prs = Presentation()

    # ==================================================
    # TITLE SLIDE
    # ==================================================

    blank = prs.slide_layouts[6]
    slide = prs.slides.add_slide(blank)

    add_background(slide, prs, theme)
    add_logo(slide, theme)

    add_title(slide, title, theme)

    add_subtitle(
        slide,
        "Generated by Mak-AI",
        theme
    )

    # ==================================================
    # CONTENT SLIDES
    # ==================================================

    for slide_data in slides:
        
        slide = prs.slides.add_slide(blank)

        add_background(slide, prs, theme)
        add_logo(slide, theme)

        add_title(
            slide,
            slide_data["title"],
            theme
        )
        image = get_slide_image(slide_data["title"])
        if image.exists():

            slide.shapes.add_picture(
                str(image),
                Inches(6.4),
                Inches(1.5),
                width=Inches(2.7)
            )

        add_bullets(
            slide,
            slide_data["content"],
            theme
        )

    output = output_dir / "presentation.pptx"

    prs.save(output)

    return output